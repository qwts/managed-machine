// NormalizeSetupName strips one optional leading "setup-" prefix and validates
// that the remaining token matches the Bash normalize_setup_name pattern
// ^[a-z0-9][a-z0-9-]*$.
func NormalizeSetupName(raw string) (string, bool) {
	name := strings.TrimPrefix(raw, "setup-")
	if name == "" {
		return "", false
	}
	for i := 0; i < len(name); i++ {
		c := name[i]
		isAlphaNum := (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')
		if i == 0 && !isAlphaNum {
			return "", false
		}
		if !isAlphaNum && c != '-' {
			return "", false
		}
	}
	return name, true
}

// LookupSetupCutover resolves raw (with an optional leading "setup-" prefix
// stripped as normalize_setup_name does) against SetupCutover by Name or
// Aliases.
func LookupSetupCutover(raw string) (SetupRoute, bool) {
	name, ok := NormalizeSetupName(raw)
	if !ok {
		return SetupRoute{}, false
	}
	for _, r := range SetupCutover {
		if r.Name == name {
			return r, true
		}
		for _, a := range r.Aliases {
			if a == name {
				return r, true
			}
		}
	}
	return SetupRoute{}, false
}

// MatchSetupCutover reports whether args invoke "setup <name|alias>" with only
// optional --json or --human presentation flags for a name or alias in
// SetupCutover.
func MatchSetupCutover(args []string) (SetupRoute, bool) {
	filtered := make([]string, 0, len(args))
	for _, a := range args {
		if a == "--json" || a == "--human" {
			continue
		}
		filtered = append(filtered, a)
	}
	if len(filtered) != 2 || filtered[0] != "setup" {
		return SetupRoute{}, false
	}
	return LookupSetupCutover(filtered[1])
}

// HasSetupRecipe reports whether the built-in catalog defines software, or a
// recipe file <software>.yaml exists as a regular file in the local source
// directory named by getenv(catalog.SourceDirEnv). A built-in definition
// cannot be redefined by a local source, so it counts as present.
func HasSetupRecipe(getenv func(string) string, software string) bool {
	if software == "" {
		return false
	}
	if catalog.BuiltinDefines(software) {
		return true
	}
	if getenv == nil {
		return false
	}
	dir := getenv(catalog.SourceDirEnv)
	if dir == "" {
		return false
	}
	info, err := os.Stat(filepath.Join(dir, software+".yaml"))
	return err == nil && info.Mode().IsRegular()
}

// RenderSetupCutoverSh renders the lib/setup-cutover.sh Bash fragment from
// SetupCutover.
func RenderSetupCutoverSh() string {
	var b strings.Builder
	b.WriteString("# Code generated by go generate ./internal/legacy; DO NOT EDIT.\n")
	b.WriteString("# S7 D9: setup <name> cutover table for bin/managed-machine.\n\n")
	b.WriteString("setup_cutover_name() {\n")
	b.WriteString("    case \"${1:-}\" in\n")
	for _, r := range SetupCutover {
		patterns := make([]string, 0, 1+len(r.Aliases))
		patterns = append(patterns, r.Name)
		patterns = append(patterns, r.Aliases...)
		fmt.Fprintf(&b, "        %s)\n            printf '%%s\\n' %q\n            return 0\n            ;;\n", strings.Join(patterns, "|"), r.Software)
	}
	b.WriteString("        *)\n")
	b.WriteString("            return 1\n")
	b.WriteString("            ;;\n")
	b.WriteString("    esac\n")
	b.WriteString("}\n")
	b.WriteString("\n# Cutover software the built-in catalog defines; no recipe file is needed.\n")
	b.WriteString("setup_cutover_builtin() {\n")
	b.WriteString("    case \"${1:-}\" in\n")
	var builtins []string
	for _, r := range SetupCutover {
		if catalog.BuiltinDefines(r.Software) {
			builtins = append(builtins, r.Software)
		}
	}
	if len(builtins) > 0 {
		fmt.Fprintf(&b, "        %s)\n            return 0\n            ;;\n", strings.Join(builtins, "|"))
	}
	b.WriteString("        *)\n")
	b.WriteString("            return 1\n")
	b.WriteString("            ;;\n")
	b.WriteString("    esac\n")
	b.WriteString("}\n")
	return b.String()
}
